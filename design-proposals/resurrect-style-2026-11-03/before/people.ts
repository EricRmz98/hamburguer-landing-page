// Cuadros: 0 esperando, 1 feliz, 2 enojado. Las reacciones solo cambian los rasgos de la cara.
// Fuente editable: scripts/sprites/customers-approved.json. Regenerar con write_people.py.
function customerFrames(waiting: string, reactions: readonly (readonly [number, number, string])[][]) {
  return [waiting, ...reactions.map((patch) => {
    const frame = rows(waiting).map((row) => [...row]);
    for (const [x, y, color] of patch) frame[y][x] = color;
    return frame.map((row) => row.join('')).join('\n');
  })];
}

